// Regenerates assets.js from the brand web app, so the collaborators app reuses the exact same design assets.
//   const A     – images (brand logos, avatar)
//   const MICON – header icons (search, bell)
// Only the keys this app uses are copied, to keep the page light.
// Usage: node scripts/sync-assets.js <path-to-brand-web-app>
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const brand = process.argv[2];
if (!brand) { console.error('Usage: node scripts/sync-assets.js <path-to-brand-web-app>'); process.exit(1); }

const ctx = {};
vm.runInNewContext(`${fs.readFileSync(path.join(brand, 'assets.js'), 'utf8')}\nthis.A=A;this.MICON=MICON;`, ctx);

function pick(obj, keys, name) {
  const out = {};
  for (const k of keys) { if (!(k in obj)) throw new Error(`${name}.${k} missing`); out[k] = obj[k]; }
  return out;
}

const A = pick(ctx.A, [
  'uberLogo', 'logo2', 'pickmeLogo', 'legoLogo', 'pepsi',   // invite brand logos
  'starbucks', 'burgerking', 'dominos', 'logo3',
  'pfAvatar',                                               // header avatar
], 'A');

const js = `/* Generated by scripts/sync-assets.js from the brand web app — do not edit by hand. */
const A = ${JSON.stringify(A, null, 1)};
const MICON = ${JSON.stringify(ctx.MICON, null, 1)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'assets.js'), js);
console.log(`assets.js written (${(js.length / 1024).toFixed(0)} KB)`);
